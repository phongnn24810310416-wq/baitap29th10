IF OBJECT_ID('dbo.KhachHang','U') IS NOT NULL DROP TABLE dbo.KhachHang;
IF OBJECT_ID('dbo.Phong','U') IS NOT NULL DROP TABLE dbo.Phong;
CREATE TABLE Phong(SoPhong VARCHAR(10) PRIMARY KEY, LoaiPhong NVARCHAR(50) NOT NULL, GiaTheoGio DECIMAL(18,2) NOT NULL CHECK(GiaTheoGio>=0), TrangThai NVARCHAR(30) NOT NULL DEFAULT N'Trống');
CREATE TABLE KhachHang(MaKH INT IDENTITY PRIMARY KEY, HoTen NVARCHAR(100) NOT NULL, CCCD VARCHAR(20) NOT NULL UNIQUE, SoDienThoai VARCHAR(15));
CREATE TABLE DichVu(MaDV INT IDENTITY PRIMARY KEY, TenDV NVARCHAR(100) NOT NULL, DonGia DECIMAL(18,2) NOT NULL CHECK(DonGia>=0));
CREATE TABLE PhieuDatPhong(MaPhieu INT IDENTITY PRIMARY KEY, SoPhong VARCHAR(10) NOT NULL REFERENCES Phong(SoPhong), MaKH INT NOT NULL REFERENCES KhachHang(MaKH), NgayNhanPhong DATETIME NOT NULL DEFAULT GETDATE(), NgayTraPhong DATETIME NULL, TongTienThanhToan DECIMAL(18,2) NOT NULL DEFAULT 0);
CREATE TABLE SuDungDichVu(MaPhieu INT NOT NULL REFERENCES PhieuDatPhong(MaPhieu), MaDV INT NOT NULL REFERENCES DichVu(MaDV), SoLuong INT NOT NULL CHECK(SoLuong>0), ThoiGian DATETIME NOT NULL DEFAULT GETDATE(), PRIMARY KEY(MaPhieu,MaDV,ThoiGian));
