IF OBJECT_ID('dbo.ChiTietHoaDon','U') IS NOT NULL DROP TABLE dbo.ChiTietHoaDon;
IF OBJECT_ID('dbo.HoaDon','U') IS NOT NULL DROP TABLE dbo.HoaDon;
IF OBJECT_ID('dbo.MonAn','U') IS NOT NULL DROP TABLE dbo.MonAn;
IF OBJECT_ID('dbo.DanhMuc','U') IS NOT NULL DROP TABLE dbo.DanhMuc;
IF OBJECT_ID('dbo.BanAn','U') IS NOT NULL DROP TABLE dbo.BanAn;
CREATE TABLE BanAn(MaBan INT IDENTITY PRIMARY KEY, TenBan NVARCHAR(50) NOT NULL, TrangThai NVARCHAR(20) NOT NULL DEFAULT N'Trống');
CREATE TABLE DanhMuc(MaDanhMuc INT IDENTITY PRIMARY KEY, TenDanhMuc NVARCHAR(100) NOT NULL);
CREATE TABLE MonAn(MaMon INT IDENTITY PRIMARY KEY, TenMon NVARCHAR(100) NOT NULL, MaDanhMuc INT NOT NULL REFERENCES DanhMuc(MaDanhMuc), DonGia DECIMAL(18,2) NOT NULL CHECK(DonGia>=0));
CREATE TABLE HoaDon(MaHoaDon INT IDENTITY PRIMARY KEY, MaBan INT NOT NULL REFERENCES BanAn(MaBan), GioVao DATETIME NOT NULL DEFAULT GETDATE(), GioRa DATETIME NULL, TongTien DECIMAL(18,2) NOT NULL DEFAULT 0, TrangThai BIT NOT NULL DEFAULT 0);
CREATE TABLE ChiTietHoaDon(MaHoaDon INT NOT NULL REFERENCES HoaDon(MaHoaDon), MaMon INT NOT NULL REFERENCES MonAn(MaMon), SoLuong INT NOT NULL CHECK(SoLuong>0), DonGia DECIMAL(18,2) NOT NULL, PRIMARY KEY(MaHoaDon,MaMon));
