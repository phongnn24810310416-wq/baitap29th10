CREATE TABLE NhaCungCap(MaNCC INT IDENTITY PRIMARY KEY, TenNCC NVARCHAR(150) NOT NULL, DienThoai VARCHAR(15) UNIQUE NULL, DiaChi NVARCHAR(255));
CREATE TABLE VatTu(MaVatTu VARCHAR(20) PRIMARY KEY, TenVatTu NVARCHAR(150) NOT NULL, DVT NVARCHAR(20), SoLuongTon DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK(SoLuongTon>=0));
CREATE TABLE PhieuKho(MaPhieu INT IDENTITY PRIMARY KEY, LoaiPhieu NVARCHAR(10) NOT NULL CHECK(LoaiPhieu IN(N'NHAP',N'XUAT')), NgayLap DATETIME NOT NULL DEFAULT GETDATE(), MaNCC INT NULL REFERENCES NhaCungCap(MaNCC), TongTien DECIMAL(18,2) NOT NULL DEFAULT 0);
CREATE TABLE ChiTietPhieuKho(MaPhieu INT NOT NULL REFERENCES PhieuKho(MaPhieu), MaVatTu VARCHAR(20) NOT NULL REFERENCES VatTu(MaVatTu), SoLuong DECIMAL(18,2) NOT NULL CHECK(SoLuong>0), DonGia DECIMAL(18,2) NOT NULL CHECK(DonGia>=0), PRIMARY KEY(MaPhieu,MaVatTu));
