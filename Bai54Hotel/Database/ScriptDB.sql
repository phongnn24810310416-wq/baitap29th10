IF OBJECT_ID('dbo.SuDungDichVu','U') IS NOT NULL DROP TABLE dbo.SuDungDichVu;
IF OBJECT_ID('dbo.PhieuDatPhong','U') IS NOT NULL DROP TABLE dbo.PhieuDatPhong;
